import AppKit
import Carbon
import ImageIO

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    let id: UUID
    var date: Date
    let source: String
    let kind: Kind
    var pinned: Bool
    let text: String?
    let html: Data?
    let png: Data?
    let paths: [String]?
    var byteCount: Int {
        let textBytes: Int = text?.utf8.count ?? 0
        let htmlBytes: Int = html?.count ?? 0
        let imageBytes: Int = png?.count ?? 0
        let pathBytes: Int = paths?.joined().utf8.count ?? 0
        return textBytes + htmlBytes + imageBytes + pathBytes
    }
    var title: String { text ?? paths?.map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", ") ?? "Hình ảnh" }
}

final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var message = ""
    @Published var enabled: Bool {
        didSet {
            defaults.set(enabled, forKey: "Clipboard.Enabled")
            lastChange = board.changeCount // Never ingest content copied before consent.
        }
    }
    @Published var exclusions: String {
        didSet { defaults.set(exclusions, forKey: "Clipboard.Exclusions") }
    }
    private let defaults: UserDefaults
    private let store: URL
    private let board: NSPasteboard
    private let onCopy: () -> Void
    private var lastChange: Int
    private var lastPrune = Date.distantPast
    private var timer: Timer?
    private var locked = false
    private var observers: [NSObjectProtocol] = []
    private let storageQueue = DispatchQueue(label: "vn.xmac.clipboard-storage", qos: .utility)
    static let maxItemBytes = 1024 * 1024
    static let maxTotalBytes = 16 * 1024 * 1024
    static let maxItems = 100

    init(defaults: UserDefaults = .standard, store: URL? = nil, board: NSPasteboard = .general,
         onCopy: @escaping () -> Void = { FinderCutPasteManager.shared.handleCopy() }) {
        self.defaults = defaults
        self.store = store ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/Xmac/Clipboard/history.json")
        self.board = board
        self.onCopy = onCopy
        lastChange = board.changeCount
        enabled = defaults.bool(forKey: "Clipboard.Enabled")
        exclusions = defaults.string(forKey: "Clipboard.Exclusions") ?? "com.1password.1password, com.agilebits.onepassword7, com.bitwarden.desktop, com.apple.Passwords, com.apple.keychainaccess"
        if let size = try? self.store.resourceValues(forKeys: [.fileSizeKey]).fileSize, size <= Self.maxTotalBytes * 2,
           let data = try? Data(contentsOf: self.store), let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            items = saved.filter { $0.byteCount <= Self.maxItemBytes }
            prune()
        }
    }

    func start() {
        guard timer == nil else { return }
        let center = DistributedNotificationCenter.default()
        observers = [
            center.addObserver(forName: NSNotification.Name("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in self?.locked = true },
            center.addObserver(forName: NSNotification.Name("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
                self?.locked = false
                self?.lastChange = self?.board.changeCount ?? 0
            }
        ]
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            guard let self else { return }
            self.poll(source: NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "", secureInput: IsSecureEventInputEnabled())
        }
    }

    func stop() {
        timer?.invalidate(); timer = nil
        observers.forEach { DistributedNotificationCenter.default().removeObserver($0) }
        observers = []
        flush()
    }
    func flush() { storageQueue.sync {} }

    static func blocked(types: Set<String>, source: String, exclusions: String, secure: Bool) -> Bool {
        let blockedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        let excluded = exclusions.split(separator: ",").map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        return secure || !types.isDisjoint(with: blockedTypes) || excluded.contains { source == $0 || source.hasPrefix($0 + ".") }
    }

    func poll(source: String, secureInput: Bool = false, now: Date = Date()) {
        if now.timeIntervalSince(lastPrune) > 3600 { prune(now: now); lastPrune = now }
        guard enabled else { return }
        let change = board.changeCount
        guard change != lastChange else { return }
        lastChange = change
        let types = Set((board.types ?? []).map(\.rawValue))
        let reportedSource = board.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")) ?? source
        guard !locked, !Self.blocked(types: types, source: source, exclusions: exclusions, secure: secureInput),
              !Self.blocked(types: types, source: reportedSource, exclusions: exclusions, secure: secureInput) else { return }
        let text = board.string(forType: .string)
        let html = board.data(forType: .html)
        let paths = (board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL])?.map(\.path)
        let png = Self.imagePNG(board.data(forType: .png), convert: false)
            ?? Self.imagePNG(board.data(forType: .tiff), convert: true)
        let item: ClipboardItem
        if let paths, !paths.isEmpty {
            item = ClipboardItem(id: UUID(), date: now, source: reportedSource, kind: .files, pinned: false, text: nil, html: nil, png: nil, paths: paths)
        } else if let text, !text.isEmpty {
            item = ClipboardItem(id: UUID(), date: now, source: reportedSource, kind: .text, pinned: false, text: text, html: html, png: nil, paths: nil)
        } else if let png, png.count <= Self.maxItemBytes, NSImage(data: png) != nil {
            item = ClipboardItem(id: UUID(), date: now, source: reportedSource, kind: .image, pinned: false, text: nil, html: nil, png: png, paths: nil)
        } else { return }
        guard board.changeCount == change, item.byteCount <= Self.maxItemBytes else { return }
        if let index = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.html == item.html && $0.png == item.png && $0.paths == item.paths }) {
            var existing = items.remove(at: index)
            existing.date = now
            items.insert(existing, at: 0)
            persist()
            return
        }
        // Pins are never silently discarded to make room for a new capture.
        guard items.filter(\.pinned).count < Self.maxItems,
              items.filter(\.pinned).reduce(0, { $0 + $1.byteCount }) + item.byteCount <= Self.maxTotalBytes else { return }
        items.insert(item, at: 0)
        prune(now: now)
        persist()
    }

    func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        prune()
        persist()
    }

    private static func imagePNG(_ data: Data?, convert: Bool) -> Data? {
        guard let data, data.count <= maxItemBytes,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 4096, height <= 4096, width * height <= 4_000_000 else { return nil }
        guard convert else { return data }
        guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let result = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(result, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), result.length <= maxItemBytes else { return nil }
        return result as Data
    }
    func remove(_ id: UUID) { items.removeAll { $0.id == id }; persist() }
    func clear() { items = []; lastChange = board.changeCount; persist() }

    func copy(_ item: ClipboardItem, plainText: Bool = false) {
        let offer = NSPasteboardItem()
        switch item.kind {
        case .text:
            offer.setString(item.text ?? "", forType: .string)
            if !plainText, let html = item.html { offer.setData(html, forType: .html) }
        case .image:
            guard let data = item.png else { return }
            offer.setData(data, forType: .png)
        case .files:
            let urls = (item.paths ?? []).filter { FileManager.default.fileExists(atPath: $0) }.map { NSURL(fileURLWithPath: $0) }
            guard urls.count == item.paths?.count else { message = L10n.text("Một số tệp không còn tồn tại."); return }
            board.clearContents()
            guard board.writeObjects(urls) else { message = L10n.text("Không thể ghi clipboard."); return }
            onCopy()
            lastChange = board.changeCount
            message = L10n.text("Đã chép danh sách tệp. Dùng ⌘V để dán.")
            return
        }
        board.clearContents()
        guard board.writeObjects([offer]) else { message = L10n.text("Không thể ghi clipboard."); return }
        onCopy()
        lastChange = board.changeCount
        message = L10n.text("Đã chép. Dùng ⌘V trong ứng dụng đích để dán.")
    }

    private func prune(now: Date = Date()) {
        let previous = items
        items.removeAll { !$0.pinned && now.timeIntervalSince($0.date) > 7 * 86400 }
        while items.count > Self.maxItems || items.reduce(0, { $0 + $1.byteCount }) > Self.maxTotalBytes {
            guard let index = items.lastIndex(where: { !$0.pinned }) else { break }
            items.remove(at: index)
        }
        if items != previous { persist() }
    }
    private func persist() {
        let snapshot = items, store = self.store
        storageQueue.async {
        do {
            let fm = FileManager.default
            try fm.createDirectory(at: store.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try JSONEncoder().encode(snapshot).write(to: store, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: store.path)
        } catch { DispatchQueue.main.async { self.message = L10n.format("Không thể lưu lịch sử: %@", error.localizedDescription) } }
        }
    }
}
