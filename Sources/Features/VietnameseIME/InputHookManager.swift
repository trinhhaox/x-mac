import Cocoa
import Carbon

public class InputHookManager: ObservableObject {
    public static let shared = InputHookManager()
    
    @Published public var isVietnameseMode: Bool = true {
        didSet {
            UserDefaults.standard.set(isVietnameseMode, forKey: "XmacIME_VietnameseMode")
        }
    }
    
    @Published public var typingMethod: TypingMethod = .telex {
        didSet {
            UserDefaults.standard.set(typingMethod.rawValue, forKey: "XmacIME_TypingMethod")
        }
    }
    
    @Published public var modernOrthography: Bool = true {
        didSet {
            UserDefaults.standard.set(modernOrthography, forKey: "XmacIME_ModernOrthography")
        }
    }
    
    /// Keystroke trace for bug reports (IMEDiagnosticLog). Deliberately not
    /// persisted: it logs typed text, so it is off again after a relaunch.
    @Published public var diagnosticLogging = false

    @Published public var excludedApps: [String] = [
        "com.apple.Terminal",
        "com.googlecode.iterm2",
        "com.apple.dt.Xcode"
    ]
    
    // Composition state below is owned by the event tap thread. The main
    // thread only asks for a reset through IMEConfigurationStore.
    private var currentBuffer: String = ""
    private var rawBuffer: String = ""
    private var eventProxy: CGEventTapProxy?
    private var seenResetGeneration = 0
    private var diagnostics = false
    private var languageSwitch = CtrlShiftToggleDetector()
    /// Private state: synthetic keys must not pick up Shift or other modifiers
    /// the user is physically holding while typing fast.
    private let eventSource = CGEventSource(stateID: .privateState)
    private var lastReplacementMachTime: UInt64 = 0
    private var globalMouseMonitor: Any?
    private var localMouseMonitor: Any?

    // Tag only the events generated by Xmac itself. A time-based suppression
    // window also drops real keystrokes from fast typists, which breaks the
    // next word and prevents macros such as `vn ` from expanding.
    static let simulatedEventMarker: Int64 = 0x584D4143 // "XMAC"

    static func isSimulatedEvent(_ event: CGEvent) -> Bool {
        event.getIntegerValueField(.eventSourceUserData) == simulatedEventMarker
    }

    static func markAsSimulated(_ event: CGEvent) {
        event.setIntegerValueField(.eventSourceUserData, value: simulatedEventMarker)
    }
    
    private init() {
        if UserDefaults.standard.object(forKey: "XmacIME_VietnameseMode") != nil {
            self.isVietnameseMode = UserDefaults.standard.bool(forKey: "XmacIME_VietnameseMode")
        }
        if let methodStr = UserDefaults.standard.string(forKey: "XmacIME_TypingMethod"),
           let method = TypingMethod(rawValue: methodStr) {
            self.typingMethod = method
        }
        if UserDefaults.standard.object(forKey: "XmacIME_ModernOrthography") != nil {
            self.modernOrthography = UserDefaults.standard.bool(forKey: "XmacIME_ModernOrthography")
        }
        setupMouseMonitors()
    }

    private func setupMouseMonitors() {
        guard globalMouseMonitor == nil else { return }
        // Passive global monitor: reset composition when user clicks outside,
        // without routing hardware mouse events through active CGEventTap.
        globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(
            matching: [.leftMouseDown, .rightMouseDown, .otherMouseDown]
        ) { _ in
            IMEConfigurationStore.shared.requestReset()
        }
        localMouseMonitor = NSEvent.addLocalMonitorForEvents(
            matching: [.leftMouseDown, .rightMouseDown, .otherMouseDown]
        ) { event in
            IMEConfigurationStore.shared.requestReset()
            return event
        }
    }
    
    /// Main thread. `resetComposition` is false when the tap thread already
    /// reset itself (Ctrl+Shift), so a late reset cannot eat the next word.
    public func toggleLanguage(resetComposition: Bool = true) {
        self.isVietnameseMode.toggle()
        let store = IMEConfigurationStore.shared
        if resetComposition { store.requestReset() }
        // Publish the new mode now instead of waiting for the Combine hop.
        store.refresh()
        SoundEffectManager.shared.play(.paste)
    }
    
    public func start() {
        GlobalEventTap.shared.start()
        setupMouseMonitors()
    }
    
    public func stop() {
        // The shared tap lives for the application lifetime.
    }

    /// Event tap thread.
    func handleEvent(type: CGEventType, event: CGEvent, proxy: CGEventTapProxy? = nil) -> Unmanaged<CGEvent>? {
        eventProxy = proxy
        defer { eventProxy = nil }
        let snapshot = IMEConfigurationStore.shared.snapshot
        diagnostics = snapshot.diagnosticLogging
        if snapshot.resetGeneration != seenResetGeneration {
            seenResetGeneration = snapshot.resetGeneration
            trace("reset: app or language changed")
            resetComposition()
        }
        if type == .leftMouseDown || type == .rightMouseDown || type == .otherMouseDown {
            languageSwitch.handleKeyDown()
            if !currentBuffer.isEmpty { trace("reset: mouse click") }
            resetComposition()
            return Unmanaged.passUnretained(event)
        }

        // Nếu đây là phím ảo do chính Xmac giả lập gửi ra, bỏ qua để không lặp vô tận.
        if Self.isSimulatedEvent(event) {
            return Unmanaged.passUnretained(event)
        }

        // Xử lý phím tắt chuyển nhanh E/V (Control + Shift)
        if type == .flagsChanged {
            let flags = event.flags
            let shouldToggle = languageSwitch.handleFlagsChanged(
                control: flags.contains(.maskControl),
                shift: flags.contains(.maskShift),
                other: flags.contains(.maskCommand) || flags.contains(.maskAlternate)
            )
            if shouldToggle {
                resetComposition()
                DispatchQueue.main.async {
                    self.toggleLanguage(resetComposition: false)
                }
            }
            return Unmanaged.passUnretained(event)
        }

        guard type == .keyDown else {
            return Unmanaged.passUnretained(event)
        }
        languageSwitch.handleKeyDown()

        guard diagnostics else { return handleKeyDown(event: event, snapshot: snapshot) }
        let before = currentBuffer
        let result = handleKeyDown(event: event, snapshot: snapshot)
        trace("key code=\(event.getIntegerValueField(.keyboardEventKeycode)) char=[\(Self.typedText(of: event))] flags=\(event.flags.rawValue) repeat=\(event.getIntegerValueField(.keyboardEventAutorepeat)) buffer=[\(before)]->[\(currentBuffer)] raw=[\(rawBuffer)] \(result == nil ? "swallowed" : "passed") app=\(snapshot.bundleIdentifier ?? "?")")
        return result
    }

    private static func typedText(of event: CGEvent) -> String {
        var length = 0
        var chars = [UniChar](repeating: 0, count: 4)
        event.keyboardGetUnicodeString(maxStringLength: 4, actualStringLength: &length, unicodeString: &chars)
        return String(utf16CodeUnits: chars, count: length)
    }

    private func trace(_ message: @autoclosure () -> String) {
        if diagnostics { IMEDiagnosticLog.log(message()) }
    }

    private func handleKeyDown(event: CGEvent, snapshot: IMETapSnapshot) -> Unmanaged<CGEvent>? {
        let isTargetWebOrElectron = snapshot.isBrowser || snapshot.isElectronOrChatApp
        if lastReplacementMachTime > 0 && isTargetWebOrElectron {
            let elapsed = mach_absolute_time() - lastReplacementMachTime
            // If the next physical key arrives in < 0.6ms after a replacement in Chrome/Zalo,
            // wait briefly so WindowServer and app message loop finish applying the synthetic keys.
            if elapsed < 600_000 {
                usleep(useconds_t((600_000 - elapsed) / 1000))
            }
            lastReplacementMachTime = 0
        }

        let effectiveConfiguration = snapshot.configuration

        let flags = event.flags
        // Nếu có Command, Option hoặc Control -> Phím tắt ứng dụng, reset buffer và bỏ qua
        if flags.contains(.maskCommand) || flags.contains(.maskAlternate) || flags.contains(.maskControl) {
            currentBuffer = ""
            rawBuffer = ""
            return Unmanaged.passUnretained(event)
        }
        
        // Kiểm tra App đang active
        if snapshot.isExcluded {
            currentBuffer = ""
            rawBuffer = ""
            return Unmanaged.passUnretained(event)
        }
        
        let keyCode = event.getIntegerValueField(.keyboardEventKeycode)

        // Di chuyển caret/focus làm buffer hiện tại không còn an toàn để thay thế.
        let contextChangingKeyCodes: Set<Int64> = [
            48,  // Tab
            53,  // Escape
            115, // Home
            116, // Page Up
            117, // Forward Delete
            119, // End
            121, // Page Down
            123, // Left Arrow
            124, // Right Arrow
            125, // Down Arrow
            126  // Up Arrow
        ]
        if contextChangingKeyCodes.contains(keyCode) {
            resetComposition()
            return Unmanaged.passUnretained(event)
        }
        
        // Phím Delete / Backspace (keyCode = 51)
        if keyCode == 51 {
            if !currentBuffer.isEmpty {
                currentBuffer.removeLast()
            }
            // Backspace edits the displayed text, not the original Telex keys.
            // Do not restore stale keys after an explicit correction.
            rawBuffer = currentBuffer
            return Unmanaged.passUnretained(event)
        }

        // Some input sources do not attach a Unicode payload to the physical
        // Space key. Detect it by the stable hardware key code before reading
        // Unicode so macro expansion still runs.
        if keyCode == 49 {
            return handleWordBoundary(character: " ", event: event, snapshot: snapshot)
        }
        if keyCode == 36 || keyCode == 76 {
            if snapshot.isBrowser || snapshot.isElectronOrChatApp {
                // Ensure recent synthetic replacement finishes committing in Zalo / web chat
                // before Enter submits the message.
                if lastReplacementMachTime > 0 {
                    usleep(500)
                    lastReplacementMachTime = 0
                }
            }
            return handleWordBoundary(character: "\n", event: event, snapshot: snapshot)
        }
        
        // Lấy ký tự Unicode
        var length = 0
        var chars = [UniChar](repeating: 0, count: 4)
        event.keyboardGetUnicodeString(maxStringLength: 4, actualStringLength: &length, unicodeString: &chars)
        
        guard length > 0, let scalar = UnicodeScalar(chars[0]) else {
            currentBuffer = ""
            rawBuffer = ""
            return Unmanaged.passUnretained(event)
        }
        
        let char = Character(scalar)
        
        // Phím phân tách từ: Space, Return, Tab, dấu câu
        if char == " " || char == "\n" || char == "\t" || ",.!?;:()[]{}\"'".contains(char) {
            return handleWordBoundary(character: char, event: event, snapshot: snapshot)
        }
        
        // Nếu đang ở chế độ Tiếng Anh (E), chỉ lưu buffer cơ bản và cho qua
        rawBuffer.append(char)
        guard effectiveConfiguration.isVietnameseMode else {
            currentBuffer.append(char)
            return Unmanaged.passUnretained(event)
        }
        
        // Xử lý Tiếng Việt qua Engine
        let (transformed, didTransform) = VietnameseEngine.shared.processWord(
            currentWord: currentBuffer,
            newChar: char,
            method: effectiveConfiguration.typingMethod,
            modernOrthography: snapshot.modernOrthography
        )
        
        if didTransform {
            let previous = currentBuffer
            currentBuffer = transformed
            // A transform that only appends the typed key needs no synthetic events.
            if transformed == previous + String(char) {
                return Unmanaged.passUnretained(event)
            }
            replaceText(previous, with: transformed, snapshot: snapshot)
            return nil // Nuốt sự kiện gốc
        } else {
            currentBuffer.append(char)
            return Unmanaged.passUnretained(event)
        }
    }

    static func macroExpansion(
        for buffer: String,
        boundaryKeyCode: Int64,
        character: Character?,
        macros: [String: String],
        enabled: Bool
    ) -> String? {
        let isSpace = boundaryKeyCode == 49 || character == " "
        guard isSpace, enabled else { return nil }
        return macros[buffer]
    }

    private func handleWordBoundary(
        character: Character,
        event: CGEvent,
        snapshot: IMETapSnapshot
    ) -> Unmanaged<CGEvent>? {
        let keyCode = event.getIntegerValueField(.keyboardEventKeycode)
        let effectiveConfiguration = snapshot.configuration
        if let expansion = Self.macroExpansion(
            for: currentBuffer,
            boundaryKeyCode: keyCode,
            character: character,
            macros: snapshot.macros,
            enabled: effectiveConfiguration.macrosEnabled
        ) {
            let oldLen = currentBuffer.count
            currentBuffer = ""
            rawBuffer = ""
            replaceWord(backspaceCount: oldLen, newText: expansion + " ", snapshot: snapshot)
            return nil
        }

        if effectiveConfiguration.isVietnameseMode,
           let restored = EnglishWordRestoration.restoration(raw: rawBuffer, composed: currentBuffer) {
            let composed = currentBuffer
            currentBuffer = ""
            rawBuffer = ""
            replaceText(composed, with: restored, snapshot: snapshot)
            // Re-post the boundary key itself (Space, Return, punctuation) through
            // the same channel, so it lands after the restored word and Return
            // still sends/submits like the physical key.
            if let boundary = event.copy() {
                Self.markAsSimulated(boundary)
                postReplacement(boundary)
            }
            return nil
        }

        currentBuffer = ""
        rawBuffer = ""
        return Unmanaged.passUnretained(event)
    }
    
    /// Edits only the part that changed: "tieng" -> "tiêng" sends 3 backspaces
    /// and "êng" instead of retyping the whole word. Fewer synthetic events
    /// means less flicker and fewer chances for an app to drop one.
    private func replaceText(_ oldText: String, with newText: String, snapshot: IMETapSnapshot) {
        let commonPrefix = zip(oldText, newText).prefix { $0 == $1 }.count
        replaceWord(
            backspaceCount: oldText.count - commonPrefix,
            newText: String(newText.dropFirst(commonPrefix)),
            snapshot: snapshot
        )
    }

    private func replaceWord(backspaceCount: Int, newText: String, snapshot: IMETapSnapshot) {
        let plan = SyntheticReplacementPlan.make(
            backspaceCount: backspaceCount,
            newText: newText,
            isBrowser: snapshot.isBrowser,
            isElectronOrChatApp: snapshot.isElectronOrChatApp
        )
        TypingLatencyMonitor.shared.recordReplacement(syntheticEvents: plan.syntheticEventCount)
        trace("replace backspaces=\(plan.backspaceCount) breaker=\(plan.leadingText != nil) text=[\(newText)] keyEvents=\(plan.textChunks.count) viaProxy=\(eventProxy != nil)")

        let isTargetWebOrElectron = snapshot.isBrowser || snapshot.isElectronOrChatApp

        if let leadingText = plan.leadingText {
            postText(leadingText)
            if isTargetWebOrElectron { usleep(120) }
        }
        // 1. Gửi backspace để xoá từ cũ
        for i in 0..<plan.backspaceCount {
            postKey(virtualKey: 51, keyDown: true)
            postKey(virtualKey: 51, keyDown: false)
            if isTargetWebOrElectron && plan.backspaceCount > 1 && i < plan.backspaceCount - 1 {
                // Micro-pause between Backspaces so Chromium/Electron event loop doesn't drop them
                usleep(120)
            }
        }

        // Safe gap between Backspaces and new text for Zalo and Chrome
        if isTargetWebOrElectron && plan.backspaceCount > 0 {
            usleep(180)
        }

        // 2. Gửi chuỗi ký tự mới
        for (idx, utf16) in plan.textChunks.enumerated() {
            postText(utf16)
            if isTargetWebOrElectron && idx < plan.textChunks.count - 1 {
                usleep(120)
            }
        }

        if isTargetWebOrElectron {
            lastReplacementMachTime = mach_absolute_time()
        }
    }

    /// Key code carried by synthetic text events. It used to be 0, the A key:
    /// typing "aw" fast keeps the physical A held while Xmac sends "ă", so
    /// apps saw a second A press during the hold, and Zalo dropped exactly
    /// those "ă" while keeping the Backspace ("tặng" became "ặng"), likely
    /// treating it as a press-and-hold repeat. The ISO § key has no letter,
    /// no accent popup and is absent from ANSI keyboards.
    static let textKeyCode: CGKeyCode = 10 // kVK_ISO_Section

    private func postText(_ utf16: [UInt16]) {
        if let keyEvent = makeKeyEvent(virtualKey: Self.textKeyCode, keyDown: true) {
            keyEvent.keyboardSetUnicodeString(stringLength: utf16.count, unicodeString: utf16)
            postReplacement(keyEvent)
        }
        postKey(virtualKey: Self.textKeyCode, keyDown: false)
    }

    private func postKey(virtualKey: CGKeyCode, keyDown: Bool) {
        if let event = makeKeyEvent(virtualKey: virtualKey, keyDown: keyDown) {
            postReplacement(event)
        }
    }

    private func makeKeyEvent(virtualKey: CGKeyCode, keyDown: Bool) -> CGEvent? {
        guard let event = CGEvent(keyboardEventSource: eventSource, virtualKey: virtualKey, keyDown: keyDown) else {
            return nil
        }
        event.flags = []
        event.timestamp = mach_absolute_time()
        Self.markAsSimulated(event)
        return event
    }

    private func postReplacement(_ event: CGEvent) {
        // Insert directly after our tap so later physical keys cannot overtake
        // the replacement by travelling through the HID pipeline first.
        if let eventProxy {
            event.tapPostEvent(eventProxy)
        } else {
            event.post(tap: .cghidEventTap)
        }
    }

    /// Event tap thread.
    private func resetComposition() {
        currentBuffer = ""
        rawBuffer = ""
    }

    /// Event tap thread: keys typed while macOS had the tap disabled reached
    /// the app unseen, so the buffer no longer matches the text on screen.
    func handleTapReenabled() {
        trace("reset: tap re-enabled after macOS disabled it")
        resetComposition()
    }

    /// Main thread.
    public func resetForApplicationChange() {
        IMEConfigurationStore.shared.requestReset()
    }
}
